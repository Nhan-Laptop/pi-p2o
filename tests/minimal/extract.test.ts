const parsed = (text: string, extra: { url?: string } = {}) => extract({ text, ...extra });
const keys = (result: ExtractResult | undefined) => result?.assets.map(asset => `${asset.kind} ${asset.key}`) ?? [];

describe('extraction registry', () => {
  it('recognizes each supported format once and leaves unrecognized text alone', () => {
    expect(parsed(nmapXml)?.extractor).toBe('nmap');
    expect(parsed(httpxJsonl)?.extractor).toBe('httpx');
    expect(parsed(nucleiJsonl)?.extractor).toBe('nuclei');
    expect(parsed(rawResponse, { url: 'https://portal.lab.test/' })?.extractor).toBe('http-response');
    expect(parsed(openapiJson)?.extractor).toBe('openapi');
    expect(parsed(packageLock)?.extractor).toMatch(/^packages:/);
    expect(parsed(pnpmLock)?.extractor).toMatch(/^packages:/);
    expect(parsed(requirements)?.extractor).toMatch(/^packages:/);
    expect(parsed(goMod)?.extractor).toMatch(/^packages:/);
    expect(parsed(cargoLock)?.extractor).toMatch(/^packages:/);
    expect(parsed(gemLock)?.extractor).toMatch(/^packages:/);
    expect(parsed(pomXml)?.extractor).toMatch(/^packages:/);
    // Not a recognized shape: prose, an empty capture, binary bytes and a raw body without the HTTP status line.
    expect(parsed('just some log output\nwith lines')).toBeUndefined();
    expect(parsed('')).toBeUndefined();
    expect(parsed('\u0000\u0000PNG\u0001\u0002')).toBeUndefined();
    expect(parsed('<html><body>no status line</body></html>', { url: 'https://portal.lab.test/' })).toBeUndefined();
    expect(EXTRACTORS.map(extractor => extractor.name)).toEqual(['openapi', 'nmap', 'nuclei', 'httpx', 'packages', 'http-response']);
  });

  it('bounds the input at 4 MiB by bytes without splitting a character and reports the row caps it applied', () => {
    expect(Buffer.byteLength(boundedText('é'.repeat(10), 10))).toBeLessThanOrEqual(10);
    const result = parsed(nmapXml)!;
    expect(result.omitted).toEqual({ assets: 0, facts: 0, hypotheses: 0, components: 0 });
    const dense = { extractor: 'test', assets: Array.from({ length: EXTRACT_MAX_ASSETS + 5 }, (_, index) => ({ kind: 'host' as const, key: `10.0.0.${index}` })),
      facts: Array.from({ length: EXTRACT_MAX_FACTS + 7 }, (_, index) => ({ asset: 0, kind: 'observed' as const, statement: `fact ${index}`, confidence: 'low' as const })),
      hypotheses: [], components: [], warnings: [], omitted: { assets: 0, facts: 0, hypotheses: 0, components: 0 } };
    const bounded = boundResult(dense);
    expect(bounded.assets).toHaveLength(EXTRACT_MAX_ASSETS);
    expect(bounded.facts).toHaveLength(EXTRACT_MAX_FACTS);
    expect(bounded.omitted.assets).toBe(5);
    expect(bounded.omitted.facts).toBe(7);
    expect(bounded.warnings.join(' ')).toMatch(/ingest bounds: 5 assets, 7 facts/);
  });
});

describe('nmap XML', () => {
  it('inventories up hosts, open ports and service versions, and counts the rest as skipped', () => {
    const result = parsed(nmapXml)!;
    expect(keys(result)).toEqual(['host 10.0.0.5', 'service 10.0.0.5:22/tcp', 'service 10.0.0.5:443/tcp']);
    expect(result.assets[0]).toMatchObject({ kind: 'host', attributes: { hostname: 'portal.lab.test', mac: '00:11:22:33:44:55', source: 'nmap' } });
    expect(result.assets[2]).toMatchObject({ kind: 'service', attributes: { port: '443', protocol: 'tcp', service: 'https', product: 'nginx', version: '1.24.0', cpe: 'cpe:/a:nginx:nginx:1.24.0' } });
    expect(result.facts.map(fact => fact.statement)).toEqual(expect.arrayContaining(['nmap: tcp/22 is open (ssh OpenSSH 8.9p1)', 'nmap: OS hint Linux 5.4 - 5.15 (98% match); a fingerprint, not a verified platform']));
    expect(result.warnings.join(' ')).toMatch(/1 host\(s\) were not up/);
    // A closed port is not inventory; it is counted, not silently dropped.
    expect(result.warnings.join(' ')).toMatch(/1 port\(s\) were closed\/filtered/);
  });
});

describe('httpx JSON/JSONL', () => {
  it('normalizes the URL identity, dedupes it and keeps the response facts as attributes', () => {
    const result = parsed(httpxJsonl)!;
    expect(keys(result)).toEqual(['endpoint https://portal.lab.test/login', 'endpoint https://portal.lab.test/api/users']);
    expect(result.assets[0]).toMatchObject({ kind: 'endpoint', label: 'Portal',
      attributes: { status: '200', server: 'nginx', tech: 'Nginx, PHP', content_type: 'text/html', tls_issuer: 'Lab CA' } });
    expect(result.warnings.join(' ')).toMatch(/1 duplicate URL row/);
    expect(result.warnings.join(' ')).toMatch(/no usable http\(s\) URL/);
    expect(result.facts[0]?.statement).toMatch(/httpx: HTTP 200 — Portal/);
  });
});

describe('nuclei JSONL — the evidence-ladder boundary', () => {
  it('records a match as an open hypothesis, never as a fact or a claim', () => {
    const result = parsed(nucleiJsonl)!;
    expect(result.facts).toEqual([]);
    // D-R1-2: the identity is the normalized URL (dot segments resolve); the hypothesis quotes the tested path raw.
    expect(result.assets.map(asset => asset.key)).toEqual(['https://portal.lab.test/bin/sh', 'https://portal.lab.test/admin']);
    expect(result.hypotheses).toHaveLength(2);
    expect(result.hypotheses[0]!.impact).toMatch(/CVE-2021-41773.*CWE-22.*CVSS 7\.5/);
    expect(result.hypotheses[0]!.statement).toMatch(/template CVE-2021-41773 \(Apache path traversal\) matched at https:\/\/portal\.lab\.test\/cgi-bin\/\.%2e\/bin\/sh — severity high/);
    expect(result.warnings.join(' ')).toMatch(/recorded as open hypotheses: a template match is a pointer to test, never a claim, case or finding/);
  });
});

describe('raw HTTP response', () => {
  const result = parsed(rawResponse, { url: 'https://portal.lab.test/' })!;

  it('reports the status, header absence and cookie names without values', () => {
    expect(result.assets[0]).toMatchObject({ kind: 'endpoint', key: 'https://portal.lab.test/',
      attributes: { status: '200', server: 'nginx', 'content-type': 'text/html; charset=utf-8', cookie_names: 'session, theme' } });
    expect(result.facts.map(fact => fact.statement)).toEqual(expect.arrayContaining([
      'http: this response did not carry security header(s): content-security-policy, strict-transport-security, x-frame-options, x-content-type-options, referrer-policy, permissions-policy — an observation about this response, not by itself a vulnerability',
      'http: response set 2 cookie name(s): session, theme (values are not retained)']));
    const serialized = JSON.stringify(result);
    expect(serialized).not.toContain('<uuid4>');
    expect(serialized).not.toMatch(/theme=dark/);
  });

  it('turns same-origin links, forms and bundle paths into route assets, one identity per path', () => {
    expect(keys(result)).toEqual(expect.arrayContaining(['route /dashboard', 'route /login', 'route /api/v1/session', 'route /api/users']));
    // An external origin and a javascript: link are not route knowledge; the query is not part of the route identity.
    expect(result.assets.some(asset => asset.key.includes('elsewhere'))).toBe(false);
    expect(result.assets.find(asset => asset.key === '/login')!.attributes).toMatchObject({ method: 'post', discoveredBy: 'form' });
    expect(result.assets.find(asset => asset.key === '/api/users')!.attributes).toMatchObject({ discoveredBy: 'js' });
  });
});

describe('OpenAPI JSON', () => {
  it('records declared servers, routes and operations as contract knowledge', () => {
    const result = parsed(openapiJson)!;
    expect(result.assets[0]).toMatchObject({ kind: 'endpoint', key: 'https://portal.lab.test/api', attributes: { source: 'openapi', role: 'declared server' } });
    const routes = result.assets.filter(asset => asset.kind === 'route');
    expect(routes.map(asset => asset.key)).toEqual(['/users/{id}', '/login']);
    expect(result.facts.map(fact => fact.kind)).toEqual(expect.arrayContaining(['configuration']));
    expect(result.facts.map(fact => fact.statement).join('\n')).toMatch(/openapi: document declares GET \/users\/\{id\} \(getUser\) — Read a user/);
    expect(result.facts.map(fact => fact.statement).join('\n')).toMatch(/2 security scheme\(s\): bearer, apiKey/);
  });
});

describe('package manifests — the component inventory', () => {
  const components = (text: string) => parsed(text)!.components.map(component => `${component.ecosystem}:${component.name}@${component.version}`);

  it('reads npm locks (v2/v3 and v1), skipping links and the root project', () => {
    const result = parsed(packageLock)!;
    expect(keys(result)).toEqual(['package npm:lodash@4.17.21', 'package npm:@scope/pkg@2.0.0']);
    expect(result.assets[0]!.attributes).toMatchObject({ name: 'lodash', version: '4.17.21', ecosystem: 'npm', manifest: 'package-lock.json' });
    expect(result.components).toHaveLength(2);
    const v1 = JSON.stringify({ lockfileVersion: 1, dependencies: { lodash: { version: '4.17.21', dependencies: { nested: { version: '1.0.0' } } } } });
    expect(components(v1)).toEqual(['npm:lodash@4.17.21', 'npm:nested@1.0.0']);
  });

  it('reads pnpm locks with peer suffixes and scoped names', () => {
    expect(components(pnpmLock)).toEqual(['npm:lodash@4.17.21', 'npm:@scope/pkg@2.0.0']);
  });

  it('reads exact pip pins and counts ranges as omitted', () => {
    const result = parsed(requirements)!;
    expect(components(requirements)).toEqual(['pypi:flask@3.0.2', 'pypi:requests@2.31.0']);
    expect(result.warnings.join(' ')).toMatch(/1 line\(s\) are not exact pins/);
  });

  it('reads go.mod require blocks and single-line requires', () => {
    expect(components(goMod)).toEqual(['go:github.com/gin-gonic/gin@v1.9.1', 'go:golang.org/x/text@v0.0.0-20240101-abcdef123456', 'go:github.com/single/dep@v1.0.0']);
  });

  it('reads Cargo.lock packages, Gemfile.lock specs and Maven dependencies', () => {
    expect(components(cargoLock)).toEqual(['cargo:serde@1.0.203', 'cargo:local-crate@0.1.0']);
    expect(components(gemLock)).toEqual(['rubygems:actioncable@7.1.3', 'rubygems:rack@3.0.8']);
    expect(components(pomXml)).toEqual(['maven:org.apache.logging.log4j:log4j-core@2.14.1']);
    // A version property reference is unresolved, not a version to guess at.
    expect(parsed(pomXml)!.warnings.join(' ')).toMatch(/1 dependency row\(s\) were unpinned, unresolved/);
  });
});
