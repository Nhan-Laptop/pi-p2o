import { invariant } from '../../policy/errors.js';
import type { FuzzStrategy } from '../types.js';
import type { SeededRandom } from './prng.js';

export const FUZZ_STRATEGIES = ['bytes', 'utf8', 'json', 'url', 'header-value', 'path'] as const;

const encoder = new TextEncoder();

/**
 * Strategy axes follow the differential-testing axes that matter for parsers and canonicalizers:
 * malformed escapes and double encoding, unicode normalization/surrogates/invalid sequences, dot
 * segments and mixed separators, duplicate/empty fields, declared-vs-actual length and terminators,
 * nesting depth and error recovery. Inputs are always bytes; the module under test decides how to
 * decode them, so the differential is about the parser's own interpretation, not the generator's.
 */
const TOKEN_POOLS: Record<Exclude<FuzzStrategy, 'bytes' | 'utf8' | 'json'>, readonly string[]> = {
  url: ['http://host', 'https://host:8443', '//host', '/', '?', '#', '@', ':', '%2f', '%252f', '%00', '..', '.', '\\', '[', ']', '=', '&', 'a', 'admin'],
  'header-value': ['\r\n', '\n', '\r', '\t', ' ', ';', ',', '"', "'", '=', '%0d%0a', 'a', '-', '_', '\u0000', 'é'],
  path: ['/', '..', '.', '%2f', '%5c', '%252f', '\\', 'C:', ':', ';', '~', 'a', '_', '-'],
};

const JSON_SCALARS: readonly string[] = ['null', 'true', 'false', '0', '-0', '1', '1e999', '9007199254740993', '0.0', '1E+2'];
const JSON_STRING_PIECES: readonly string[] = ['__proto__', 'constructor', 'prototype', 'a', '', '\\ud800', '\\u0000', 'ß', '💥', 'a\u0301'];
const JSON_KEYS: readonly string[] = ['a', 'a', '__proto__', 'constructor', 'key', '', 'b'];

// Syntactically invalid or non-canonical UTF-8 sequences: overlong forms, encoded surrogates,
// truncated multi-byte sequences, BOMs and raw control/NUL bytes.
const INVALID_UTF8: readonly (readonly number[])[] = [
  [0xc0, 0xaf], [0xed, 0xa0, 0x80], [0xed, 0xbf, 0xbf], [0xe2, 0x82], [0xf0, 0x28, 0x8c, 0x28],
  [0xef, 0xbb, 0xbf], [0xfe, 0xff], [0x00], [0x0d, 0x0a], [0x80], [0xff],
];

/** Bound a generated byte string to the case budget (hard truncation, never a silent re-roll). */
function bounded(bytes: Uint8Array, limit: number): Uint8Array {
  return bytes.length <= limit ? bytes : bytes.slice(0, limit);
}

/**
 * Length distribution: empty/short inputs stay common (they shrink cheaply and isolate a single
 * delimiter), while occasional long inputs exercise length/truncation behaviour.
 */
function pickLength(rng: SeededRandom, limit: number): number {
  const draw = rng.int(4);
  if (draw === 0) return rng.int(Math.min(limit, 4));
  if (draw === 1) return Math.min(limit, 1 + rng.int(Math.min(limit, 8)));
  if (draw === 2) return Math.min(limit, 1 + rng.int(Math.min(limit, 32)));
  return 1 + rng.int(limit);
}

function bytesCase(rng: SeededRandom, limit: number): Uint8Array {
  const length = pickLength(rng, limit);
  const out = new Uint8Array(length);
  for (let index = 0; index < length; index += 1) {
    const draw = rng.int(8);
    if (draw === 0) out[index] = 0x00; // NUL is a high-value terminator/truncation axis
    else if (draw === 1) out[index] = rng.pick([0x0d, 0x0a, 0x25, 0x2e, 0x2f, 0x5c, 0x22, 0x27, 0x7f, 0x80, 0xff]);
    else out[index] = rng.int(256);
  }
  return out;
}

function utf8Case(rng: SeededRandom, limit: number): Uint8Array {
  const parts: number[] = [];
  const units = 1 + rng.int(6);
  for (let index = 0; index < units && parts.length < limit; index += 1) {
    const draw = rng.int(10);
    const codePoint = draw < 4 ? rng.int(0x80) : draw < 6 ? 0x80 + rng.int(0x780) : draw < 7 ? 0x800 + rng.int(0xf780) : undefined;
    if (codePoint !== undefined) parts.push(...encoder.encode(String.fromCodePoint(codePoint)));
    else parts.push(...rng.pick(INVALID_UTF8));
  }
  return bounded(Uint8Array.from(parts), limit);
}

function jsonCase(rng: SeededRandom, limit: number): string {
  const build = (depth: number): string => {
    const choice = depth >= 3 ? rng.int(6) : rng.int(8);
    if (choice === 0) return rng.pick(JSON_SCALARS);
    if (choice === 1) return `"${rng.pick(JSON_STRING_PIECES)}"`;
    if (choice === 2) return `["${rng.pick(JSON_STRING_PIECES)}"]`.slice(0, 32);
    if (choice === 3) return `{"${rng.pick(JSON_KEYS)}":${rng.pick(JSON_SCALARS)}}`;
    if (choice === 4) return `[${build(depth + 1)},${build(depth + 1)}]`;
    if (choice === 5) return `[${build(depth + 1)},]`; // trailing comma: recovery axis
    if (choice === 6) return `{"${rng.pick(JSON_KEYS)}":${build(depth + 1)},"${rng.pick(JSON_KEYS)}":${build(depth + 1)}}`;
    return `{${build(depth + 1)}}`; // keyless object: rejected or repaired depending on the parser
  };
  const text = build(0);
  return text.length <= limit ? text : text.slice(0, limit);
}

function textCase(rng: SeededRandom, strategy: 'url' | 'header-value' | 'path', limit: number): string {
  const pool = TOKEN_POOLS[strategy];
  const pieces: string[] = [];
  const count = 1 + rng.int(strategy === 'path' ? 8 : 5);
  for (let index = 0; index < count; index += 1) pieces.push(rng.pick(pool));
  if (strategy === 'url' && rng.bool(0.4)) pieces.unshift(rng.pick(['http://host', 'https://host:8443', 'ftp://host']));
  if (strategy === 'path' && rng.bool(0.5)) pieces.unshift('/');
  let text = pieces.join('');
  while (encoder.encode(text).length > limit && text.length > 0) text = text.slice(0, -1);
  return text;
}

export function generateCase(rng: SeededRandom, strategy: FuzzStrategy, maxBytes: number): Uint8Array {
  invariant(Number.isSafeInteger(maxBytes) && maxBytes >= 1 && maxBytes <= 65536, 'INVALID_INPUT', 'maxInputBytes must be an integer in [1, 65536]');
  switch (strategy) {
    case 'bytes': return bytesCase(rng, maxBytes);
    case 'utf8': return utf8Case(rng, maxBytes);
    case 'json': return bounded(encoder.encode(jsonCase(rng, maxBytes)), maxBytes);
    case 'url': return bounded(encoder.encode(textCase(rng, 'url', maxBytes)), maxBytes);
    case 'header-value': return bounded(encoder.encode(textCase(rng, 'header-value', maxBytes)), maxBytes);
    case 'path': return bounded(encoder.encode(textCase(rng, 'path', maxBytes)), maxBytes);
    default: invariant(false, 'INVALID_INPUT', 'Unknown fuzz strategy');
  }
}
