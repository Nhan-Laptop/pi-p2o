#!/usr/bin/env node
// Publish portable, bounded validation evidence without RPC thinking streams, auth, or user challenge content.
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { resolve, join, basename } from 'node:path';
import { createHash } from 'node:crypto';
const source = resolve(process.argv[2] ?? 'tmp/skill-upgrade');
const destination = resolve(process.argv[3] ?? 'research/runtime/skill-upgrade');
await mkdir(destination, { recursive: true });
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const portable = value => typeof value === 'string' ? value.replaceAll(process.env.HOME ?? '/home/unknown', '${HOME}')
  : Array.isArray(value) ? value.map(portable) : value && typeof value === 'object'
    ? Object.fromEntries(Object.entries(value).map(([k,v]) => [k, portable(v)])) : value;
const output = async (name, value) => writeFile(join(destination, name), JSON.stringify(portable(value), null, 2) + '\n');
const manifest = { version: 1, note: 'Original raw files remain in ignored local storage. No RPC messages/thinking streams or user challenge source are published.', artifacts: [] };
const directories = ['campaign', 'campaign-v2', 'campaign-final-C', ...(await readdir(source)).filter(name => name.startsWith('clean-campaign-'))];
for (const directory of directories) {
  const root = join(source, directory);
  const files = await readdir(root).catch(() => []);
  if (!files.length) continue;
  const runs = [];
  for (const name of files.filter(name => name.endsWith('.json')).sort()) {
    const bytes = await readFile(join(root, name));
    const data = JSON.parse(bytes.toString('utf8'));
    if (data.schema !== 'p2o-bench-run/1') continue;
    manifest.artifacts.push({ path: `${directory}/${name}`, sha256: digest(bytes) });
    const arm = { id: data.arm.id, revision: data.arm.revision, hashes: data.arm.hashes, skills: data.arm.skills };
    const fixture = { name: data.fixture.name, variant: data.fixture.variant, objective: data.fixture.objective, sourceHash: data.fixture.sourceHash, truthSha256: data.fixture.truthSha256 };
    const messages = JSON.parse(await readFile(join(root, name.replace(/\.json$/, '.messages.json')), 'utf8'));
    const finishIndex = messages.findLastIndex(m => m.role === 'toolResult' && m.toolName === 'p2o_finish' && !m.isError);
    const finalReport = messages.slice(finishIndex + 1).filter(m => m.role === 'assistant')
      .flatMap(m => typeof m.content === 'string' ? [m.content] : (m.content ?? []).filter(b => b.type === 'text').map(b => b.text)).join('\n');
    let candidates = [], receipts = [];
    const exportName = name.replace(/\.json$/, '.export.json');
    if (files.includes(exportName)) {
      const bytes = await readFile(join(root, exportName));
      const payload = JSON.parse(bytes.toString('utf8'));
      candidates = (payload.records ?? []).filter(r => r.kind === 'candidate');
      receipts = (payload.records ?? []).filter(r => r.kind === 'evidence');
      manifest.artifacts.push({ path: `${directory}/${exportName}`, sha256: digest(bytes) });
    }
    runs.push({ runId: data.runId, orderIndex: data.orderIndex, arm, fixture, config: data.config,
      objectiveWrapperSha256: data.objectiveWrapper?.sha256, startedAt: data.startedAt, finishedAt: data.finishedAt,
      wallMs: data.wallMs, outcome: data.outcome, checks: data.checks, usage: data.usage,
      screeningScore: data.score, finalReport: finalReport.slice(0, 30000), finalReportTruncated: finalReport.length > 30000,
      skillReads: data.extraction?.skillReads, candidates, receipts,
      warning: 'Lexical screening is not a quality verdict. See reviewer-assisted adjudication and fixture-truth limitations.' });
  }
  const summaryName = files.find(name => name.endsWith('.summary.json'));
  const bytes = summaryName ? await readFile(join(root, summaryName)) : undefined;
  if (bytes) manifest.artifacts.push({ path: `${directory}/${summaryName}`, sha256: digest(bytes) });
  const clean = directory.startsWith('clean-campaign-');
  await output(`${directory}.json`, { version: 1,
    qualityValidity: clean ? 'Clean manifest-only fixture copying; user-stopped partial study; lexical scores still require adjudication'
      : 'Confounded: generated bytecode was copied but omitted from the pre-run manifest. Mechanism evidence only, not a clean skill-quality comparison.',
    summary: bytes ? JSON.parse(bytes) : { partial: true, completedReceipts: runs.length, plannedRuns: 18, stopReason: 'User requested finalization with partial benchmark' },
    runs: runs.sort((a, b) => a.orderIndex - b.orderIndex).map(r => clean ? r : { runId: r.runId, arm: r.arm.id, fixture: r.fixture.name, variant: r.fixture.variant, outcome: r.outcome, checks: r.checks, wallMs: r.wallMs, usage: r.usage }),
    rawRetention: 'Original receipts, messages and exports remain in ignored local validation storage; no original artifact was deleted.' });
}
for (const directory of ['holdout-verified', 'installed-recipe-v2']) {
  const root = join(source, directory);
  for (const name of await readdir(root).catch(() => [])) {
    if (!name.startsWith('run-')) continue;
    const run = join(root, name);
    const bytes = await readFile(join(run, 'summary.json')).catch(() => undefined);
    if (!bytes) continue;
    const summary = JSON.parse(bytes);
    const evidenceBytes = await readFile(join(run, 'evidence.json'));
    const evidence = JSON.parse(evidenceBytes);
    const runtime = JSON.parse(await readFile(join(run, 'runtime.json')));
    // Only metadata for the user-supplied challenge: no source/output excerpts, generated probes or candidate prose.
    await output(`${directory}.json`, {
      status: summary.status, model: summary.model, elapsedMs: summary.elapsedMs,
      extensionSha256: summary.extensionSha256, sourceHashes: summary.originalHashes,
      image: summary.image ?? evidence.manifest.image, rulesHash: summary.rulesHash, outcome: summary.outcome,
      evidenceSha256: digest(evidenceBytes), records: evidence.records.length,
      receiptCount: evidence.records.filter(r => r.kind === 'evidence').length,
      knowledgeReads: evidence.records.filter(r => r.kind === 'lifecycle' && r.text.startsWith('skill_read ')).map(r => ({ by: r.by, text: r.text })),
      workerResults: summary.workers?.map(w => ({ workerId: w.workerId, reported: w.reported, commandsUsed: w.commandsUsed, confidence: w.confidence, dynamicGapRecorded: Boolean(w.blocked) })),
      candidateStates: evidence.records.filter(r => r.kind === 'candidate').map(r => ({ id: r.id, by: r.by, closure: r.data.closure, execution: r.data.execution, proof: r.data.proof, policyBasis: r.data.policyBasis, supersedes: r.supersedes })),
      cleanup: runtime.cleanup,
    });
    manifest.artifacts.push({ path: `${directory}/${name}/summary.json`, sha256: digest(bytes) }, { path: `${directory}/${name}/evidence.json`, sha256: digest(evidenceBytes) });
  }
}
for (const name of ['baseline.json', 'native-installed-skills.json', 'tool-probes.json', 'semgrep-validate-diagnostic.json']) {
  const bytes = await readFile(join(source, name)).catch(() => undefined);
  if (!bytes) continue;
  manifest.artifacts.push({ path: name, sha256: digest(bytes) });
  await output(basename(name), JSON.parse(bytes));
}
for (const name of ['combined-summary.json', 'USER-STOP.json', 'stop-cleanup-audit.json', 'own-label-resources.json', 'INTERRUPTED-ATTEMPTS.json', 'AUDIT.json']) {
  const bytes = await readFile(join(source, 'clean-study', name)).catch(() => undefined);
  if (!bytes) continue;
  manifest.artifacts.push({ path: `clean-study/${name}`, sha256: digest(bytes) });
  await output(`clean-study-${name.toLowerCase()}`, JSON.parse(bytes));
}
await output('manifest.json', manifest);
console.log(`Archived ${manifest.artifacts.length} source artifacts into ${destination}`);
